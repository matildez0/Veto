const state = { lang: 'pt' };
try {
  const guardada = localStorage.getItem(LANG_KEY);
  if (guardada && TRANSLATIONS[guardada]) state.lang = guardada;
} catch (erro) { /* sem armazenamento: vale só nesta visita */ }

// Traduz um texto do app.js. Os {0}, {1}… são substituídos pelos valores de "args".
function tt(texto, args) {
  let saida = texto;
  if (state.lang === 'en' && Object.prototype.hasOwnProperty.call(PHRASES_EN, texto)) saida = PHRASES_EN[texto];
  if (args && args.length) saida = saida.replace(/\{(\d+)\}/g, (_, i) => (args[i] ?? ''));
  return saida;
}

// Idioma das datas
function dateLocale() {
  return state.lang === 'en' ? 'en-GB' : 'pt-PT';
}

const normalizar = (texto) => texto.replace(/\s+/g, ' ').trim();
const procurar = (chave) => (state.lang === 'en' && Object.prototype.hasOwnProperty.call(PHRASES_EN, chave) ? PHRASES_EN[chave] : null);

function applyLanguage() {
  const lang = TRANSLATIONS[state.lang] ? state.lang : 'pt';
  const entries = TRANSLATIONS[lang];

  document.documentElement.lang = lang === 'en' ? 'en' : 'pt-PT';

  // Textos com chave (data-i18n)
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const valor = entries[element.dataset.i18n];
    if (valor === undefined) return;
    if (element.hasAttribute('data-i18n-html')) {
      if (!element.disabled) element.innerHTML = valor; // não mexe no botão durante a análise
    } else {
      element.textContent = valor;
    }
  });

  // Textos em que o português é a chave (data-t)
  document.querySelectorAll('[data-t]').forEach((element) => {
    if (element.dataset.pt === undefined) element.dataset.pt = element.textContent;
    const traduzido = procurar(normalizar(element.dataset.pt));
    if (traduzido === null) element.textContent = element.dataset.pt;
    else {
      const lead = element.dataset.pt.match(/^\s*/)[0];
      const trail = element.dataset.pt.match(/\s*$/)[0];
      element.textContent = lead + traduzido + trail;
    }
  });

  // Atributos (placeholder, aria-label, title)
  document.querySelectorAll('[data-t-attr]').forEach((element) => {
    element.dataset.tAttr.split(' ').filter(Boolean).forEach((atributo) => {
      const guarda = `pt${atributo.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())}`;
      if (element.dataset[guarda] === undefined) element.dataset[guarda] = element.getAttribute(atributo) || '';
      const traduzido = procurar(normalizar(element.dataset[guarda]));
      element.setAttribute(atributo, traduzido === null ? element.dataset[guarda] : traduzido);
    });
  });

  const toggle = document.getElementById('language-toggle');
  if (toggle) {
    toggle.textContent = entries['language.toggle'];
    toggle.setAttribute('aria-label', entries['language.label']);
  }

  // O app.js volta a desenhar os textos que cria
  document.dispatchEvent(new CustomEvent('veto:languagechange', { detail: { lang } }));
}

function initLanguageToggle() {
  const toggle = document.getElementById('language-toggle');
  if (!toggle || toggle.dataset.ligado) return;
  toggle.dataset.ligado = '1';
  toggle.addEventListener('click', () => {
    state.lang = state.lang === 'pt' ? 'en' : 'pt';
    try { localStorage.setItem(LANG_KEY, state.lang); } catch (erro) { /* ignorar */ }
    applyLanguage();
  });
}

// Este script vem antes do app.js: aplica já o idioma guardado, para o primeiro desenho sair certo.
initLanguageToggle();
if (state.lang !== 'pt') applyLanguage();
document.addEventListener('DOMContentLoaded', () => { initLanguageToggle(); applyLanguage(); });
